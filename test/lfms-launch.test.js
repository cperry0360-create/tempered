import { test } from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8')

test('Glass sweep keeps the supplied LFMS artwork and the approved rounded sweeper',()=>{
  const h=read('index.html')
  assert.match(h,/class="lfms-launch__mark" src="\.\/branding\/lfms\/logo-mark\.svg"/)
  assert.match(h,/class="lfms-launch__wordmark" src="\.\/branding\/lfms\/logo-wordmark\.svg"/)
  assert.match(h,/class="lfms-launch__cracks"/)
  assert.match(h,/class="lfms-launch__shards"/)
  assert.match(h,/class="lfms-launch__sweeper"/)
  assert.match(h,/class="lfms-launch__sweeper-body"/)
  assert.match(h,/class="lfms-launch__sweeper-arm lfms-launch__sweeper-arm--high"/)
  assert.match(h,/class="lfms-launch__sweeper-arm lfms-launch__sweeper-arm--low"/)
  assert.match(h,/class="lfms-launch__broom"/)
  assert.match(read('branding/lfms/logo-wordmark.svg'),/viewBox="205 547 1125 235"/)
  assert.match(read('branding/lfms/logo-mark.svg'),/viewBox="435 167 675 387"/)
  assert.doesNotMatch(h,/lfms-launch__barbell|lfms-launch__plate|lfms-launch__lift-tab|lfms-launch__flash|lfms-launch__lockline/)
})

test('mark slams, glass clears in three slow pushes, then the real logo hands off',()=>{
  const c=read('src/brand.css'),js=read('src/main.js')
  assert.match(c,/animation:lfms-glass-mark-slam 650ms/)
  assert.match(c,/animation:lfms-glass-wordmark 420ms/)
  assert.match(c,/animation:lfms-glass-crack 980ms/)
  assert.match(c,/animation:lfms-glass-shard-fall 760ms/)
  assert.match(c,/animation:lfms-glass-sweeper 2640ms/)
  assert.match(c,/animation:lfms-glass-tool 2640ms/)
  assert.match(c,/animation:lfms-glass-pile 2640ms/)
  assert.match(c,/@keyframes lfms-glass-sweeper/)
  assert.match(c,/40%\s*\{[^}]*transform:translate3d\(148px/)
  assert.match(c,/47\.3%\s*\{[^}]*transform:translate3d\(153px/)
  assert.match(c,/70\.8%\s*\{[^}]*transform:translate3d\(240px/)
  assert.match(c,/100%\s*\{[^}]*transform:translate3d\(439px/)
  assert.match(c,/@keyframes lfms-glass-tool/)
  assert.match(c,/47\.3%\s*\{transform:rotate\(-8deg\)/)
  assert.match(c,/70\.8%\s*\{transform:rotate\(-8deg\)/)
  assert.match(js,/LFMS_GLASS_SWEEP_MIN_MS = 4550/)
  assert.match(js,/LFMS_GLASS_SWEEP_EXIT_MS = 340/)
  assert.match(js,/runBrandHandoff\(launch, \{ duration: LFMS_HANDOFF_MS \}\)/)
  assert.match(js,/LFMS_GLASS_SWEEP_MIN_MS - \(performance\.now\(\) - splashStarted\)/)
  assert.match(js,/setTimeout\(finish, LFMS_GLASS_SWEEP_EXIT_MS\)/)
  assert.match(js,/setTimeout\(dismissSplash, 8000\)/)
  assert.ok(js.indexOf('await dismissSplash()')<js.indexOf('await installWeeklyRecapRuntime(context)'))
})

test('offline PWA includes source brand assets and remains one app',()=>{
  const sw=read('sw.js'),f=read('src/lfms-finish.css')
  for(const asset of ['branding/lfms/logo-wordmark.svg','branding/lfms/logo-mark.svg','src/brand.css','src/lfms-finish.css'])
    assert.ok(sw.includes("'./"+asset+"'"))
  for(const cls of ['today2__pills','train2__pills','fn2__pills','progress-views']) assert.ok(f.includes(cls))
})
